def system_prompt():
    return (
        "قارن بين ملفي PDF وفقًا لسؤال المستخدم، مع الاعتماد على المقتطفات المقدمة فقط. "
        "وضّح أوجه التشابه والاختلاف ذات الصلة. إذا لم تكفِ المعلومات في أحد الملفين أو كليهما، فاذكر ذلك. "
        "إذا كانت المقتطفات كافية، فقارن مباشرةً دون ملاحظات عن كفاية المعلومات أو الحاجة إلى مزيد من التفاصيل. "
        "لا تختلق معلومات. أجب باللغة العربية فقط، حتى لو كان السؤال أو المقتطفات بلغة أخرى، "
        "واستخدم Markdown موجزًا."
    )


def task_prompt(query: str, files: list[dict]):
    sections = []
    for file in files:
        excerpts = "\n\n".join(file["excerpts"]) or "لم يُعثر على مقتطفات ذات صلة."
        sections.append(f"الملف: {file['name']}\n{excerpts}")
    return f"سؤال المقارنة: {query}\n\n" + "\n\n".join(sections)
